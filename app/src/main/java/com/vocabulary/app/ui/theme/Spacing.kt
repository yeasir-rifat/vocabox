package com.vocabulary.app.ui.theme

import androidx.compose.ui.unit.dp

/** Spacing scale used across all screens. */
object Spacing {
    val Micro = 4.dp       // icon-to-text, stacked labels
    val Compact = 8.dp     // chip gaps, tight rows
    val Standard = 12.dp   // gaps between related cards
    val Content = 16.dp    // screen edge padding
    val Card = 20.dp       // card internal padding
    val Section = 24.dp    // between sections
    val Major = 32.dp      // major separation
    /** Minimum touch target. */
    val Target = 48.dp
}
